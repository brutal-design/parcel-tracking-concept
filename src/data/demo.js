// 20451234567890 -> 20 4512 3456 7890
export function formatTtn(digits) {
  return digits.replace(/^(\d{2})(\d{0,4})(\d{0,4})(\d{0,4}).*$/, (_, a, b, c, d) => [a, b, c, d].filter(Boolean).join(' '));
}
